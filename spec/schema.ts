// Reads spec/protocol.schema.json, renders it as TypeScript, and validates values against it.
// Only the JSON Schema subset the protocol schema uses is supported.
import { join } from "node:path";

export type Schema = {
  $ref?: string;
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: Schema | boolean;
  items?: Schema;
  minItems?: number;
  pattern?: string;
  anyOf?: Schema[];
  oneOf?: Schema[];
  allOf?: Schema[];
  not?: Schema;
  description?: string;
  "x-tsType"?: string;
};

export interface ProtocolSchema {
  "x-protocolVersion": number;
  "x-errorCodes": Record<string, number>;
  $defs: Record<string, Schema>;
}

export const SCHEMA_PATH = join(import.meta.dir, "protocol.schema.json");
export const GENERATED_PATH = join(import.meta.dir, "..", "protocol", "types.generated.ts");

export async function loadSchema(path = SCHEMA_PATH): Promise<ProtocolSchema> {
  return (await Bun.file(path).json()) as ProtocolSchema;
}

const refName = (ref: string) => ref.replace(/^#\/\$defs\//, "");
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

// ---------------------------------------------------------------------------
// TypeScript rendering
// ---------------------------------------------------------------------------

function wrap(ts: string) {
  return / [|&] /.test(ts) ? `(${ts})` : ts;
}

function doc(s: Schema, indent: string) {
  return s.description ? `${indent}/** ${s.description} */\n` : "";
}

function objectTs(s: Schema, indent: string): string {
  const props = Object.entries(s.properties ?? {});
  const extra = s.additionalProperties;
  if (props.length === 0) {
    if (extra === false) return "Record<string, never>";
    return `{ [key: string]: ${typeof extra === "object" ? toTs(extra, indent) : "unknown"} }`;
  }
  const req = new Set(s.required ?? []);
  const inner = indent + "  ";
  const lines = props.map(([k, v]) => {
    const key = IDENT.test(k) ? k : JSON.stringify(k);
    return `${doc(v, inner)}${inner}${key}${req.has(k) ? "" : "?"}: ${toTs(v, inner)};`;
  });
  if (typeof extra === "object") lines.push(`${inner}[key: string]: ${toTs(extra, inner)};`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

export function toTs(s: Schema, indent = ""): string {
  if (s["x-tsType"]) return s["x-tsType"];
  if (s.$ref) return refName(s.$ref);
  if ("const" in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  const union = s.anyOf ?? s.oneOf;
  if (union) return union.map((u) => wrap(toTs(u, indent))).join(" | ");
  if (s.allOf) return s.allOf.map((u) => wrap(toTs(u, indent))).join(" & ");
  if (Array.isArray(s.type)) return s.type.map((t) => toTs({ ...s, type: t }, indent)).join(" | ");
  switch (s.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${wrap(s.items ? toTs(s.items, indent) : "unknown")}[]`;
    case "object":
      return objectTs(s, indent);
  }
  return "unknown";
}

/** Renders the whole schema as a TypeScript module (protocol/types.generated.ts). */
export function generate(schema: ProtocolSchema): string {
  const out = [
    "// GENERATED by spec/generate.ts from spec/protocol.schema.json. Do not edit.",
    "// The public import stays protocol/types.ts; spec/schema.test.ts keeps both in agreement.",
    "",
    `export const PROTOCOL_VERSION = ${schema["x-protocolVersion"]} as const;`,
    "",
    "export const ErrorCode = {",
    ...Object.entries(schema["x-errorCodes"]).map(([k, v]) => `  ${k}: ${v},`),
    "} as const;",
  ];
  for (const [name, s] of Object.entries(schema.$defs)) {
    out.push("");
    if (s.description) out.push(`/** ${s.description} */`);
    const isPlainObject = s.type === "object" && !s["x-tsType"] && Object.keys(s.properties ?? {}).length > 0;
    out.push(isPlainObject ? `export interface ${name} ${toTs(s)}` : `export type ${name} = ${toTs(s)};`);
  }
  return out.join("\n") + "\n";
}

// ---------------------------------------------------------------------------
// Validation (used by the conformance suite)
// ---------------------------------------------------------------------------

function typeOf(v: unknown): string {
  if (v === null) return "null";
  if (Array.isArray(v)) return "array";
  if (typeof v === "number") return Number.isInteger(v) ? "integer" : "number";
  return typeof v;
}

function typeMatches(t: string, v: unknown) {
  const actual = typeOf(v);
  return t === actual || (t === "number" && actual === "integer");
}

/** Returns a list of problems; empty means `value` matches `s`. */
export function validate(schema: ProtocolSchema, s: Schema, value: unknown, path = "$"): string[] {
  if (s.$ref) return validate(schema, schema.$defs[refName(s.$ref)]!, value, path);
  const errs: string[] = [];
  if ("const" in s && JSON.stringify(s.const) !== JSON.stringify(value)) errs.push(`${path}: expected ${JSON.stringify(s.const)}`);
  if (s.enum && !s.enum.some((e) => JSON.stringify(e) === JSON.stringify(value))) errs.push(`${path}: not one of ${JSON.stringify(s.enum)}`);
  if (s.type) {
    const types = Array.isArray(s.type) ? s.type : [s.type];
    if (!types.some((t) => typeMatches(t, value))) return [...errs, `${path}: expected ${types.join("|")}, got ${typeOf(value)}`];
  }
  if (s.pattern && typeof value === "string" && !new RegExp(s.pattern).test(value)) errs.push(`${path}: does not match ${s.pattern}`);
  if (s.allOf) for (const sub of s.allOf) errs.push(...validate(schema, sub, value, path));
  if (s.anyOf && !s.anyOf.some((sub) => validate(schema, sub, value, path).length === 0)) errs.push(`${path}: matches no anyOf branch`);
  if (s.oneOf && s.oneOf.filter((sub) => validate(schema, sub, value, path).length === 0).length !== 1)
    errs.push(`${path}: must match exactly one oneOf branch`);
  if (s.not && validate(schema, s.not, value, path).length === 0) errs.push(`${path}: matches a forbidden shape`);
  if (Array.isArray(value)) {
    if (s.minItems !== undefined && value.length < s.minItems) errs.push(`${path}: fewer than ${s.minItems} items`);
    if (s.items) value.forEach((v, i) => errs.push(...validate(schema, s.items!, v, `${path}[${i}]`)));
  } else if (value && typeof value === "object") {
    const obj = value as Record<string, unknown>;
    for (const k of s.required ?? []) if (!(k in obj)) errs.push(`${path}: missing ${k}`);
    for (const [k, v] of Object.entries(obj)) {
      const prop = s.properties?.[k];
      if (prop) errs.push(...validate(schema, prop, v, `${path}.${k}`));
      else if (s.additionalProperties === false) errs.push(`${path}: unexpected ${k}`);
      else if (typeof s.additionalProperties === "object") errs.push(...validate(schema, s.additionalProperties, v, `${path}.${k}`));
    }
  }
  return errs;
}

/** Validates against a named definition, e.g. validateDef(schema, "InitializeResult", x). */
export function validateDef(schema: ProtocolSchema, name: string, value: unknown): string[] {
  const def = schema.$defs[name];
  if (!def) throw new Error(`unknown schema definition: ${name}`);
  return validate(schema, def, value);
}
